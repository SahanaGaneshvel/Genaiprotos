"""Schemas for the Report Agent."""

from __future__ import annotations

from pydantic import BaseModel, Field


class ReportNarrative(BaseModel):
    """The only part of the report written by the LLM: prose that connects the evidence.
    Tables, methodology and references are generated by code from structured state."""

    executive_summary: str = Field(description="4-6 sentences with [S#] citations")
    comparative_analysis: str = Field(description="1-2 paragraphs interpreting the comparison table, with [S#]")
    benchmark_discussion: str = Field(description="1 paragraph on what the verified benchmarks do/don't show")
    deployment_considerations: list[str] = Field(default_factory=list, max_length=8)
    limitations_and_risks: list[str] = Field(default_factory=list, max_length=8)
    recommendations: list[str] = Field(default_factory=list, max_length=6)


class ReportOutput(BaseModel):
    markdown: str
    narrative_generated: bool = True
    removed_citations: list[str] = Field(default_factory=list, description="invalid [S#] stripped from LLM text")
    removed_claims: list[str] = Field(
        default_factory=list, description="narrative sentences dropped: model attributed to a source that never mentions it"
    )
    citation_check: dict = Field(default_factory=dict)
    insufficient_evidence: bool = False
